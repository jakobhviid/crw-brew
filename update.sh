#!/usr/bin/env bash
# Regenerate the Homebrew formula for crw from upstream's GitHub releases, AND
# build an x86_64 Linux *bottle* so `brew install` pours it with no C compiler
# (Homebrew-on-Linux requires one for non-bottled formulae). macOS and other
# arches install the upstream tarball directly.
#
# Upstream publishes a per-platform tarball plus a SHA256SUMS manifest — already
# the hash Homebrew wants — so each asset is verified against that manifest and
# the value reused verbatim. The linux/x64 tarball is repackaged into a bottle
# (no compilation, just the keg layout Homebrew would have installed).
#
# Written for bash 3.2 (no associative arrays) so it runs on stock macOS as well
# as in CI.
#
# Usage: ./update.sh [OUTPUT.rb]     (default: crw.rb)
# Outputs the version on stdout; writes the bottle to $WORK (default ./build).
# Requires: curl, jq, tar, and sha256sum (Linux) or shasum (macOS).
set -euo pipefail

UPSTREAM="us/crw"
OUT="${1:-crw.rb}"
REPO="jakobhviid/crw-brew" # where the Linux bottle is released
WORK="${WORK:-$(pwd)/build}"

# Linux CI has sha256sum, macOS has shasum. Support both so local bumps work.
if command -v sha256sum >/dev/null 2>&1; then
  sha256of() { sha256sum "$1" | cut -d' ' -f1; }
else
  sha256of() { shasum -a 256 "$1" | cut -d' ' -f1; }
fi

tag="$(curl -fsSL "https://api.github.com/repos/${UPSTREAM}/releases/latest" | jq -r '.tag_name')"
[ -n "$tag" ] && [ "$tag" != "null" ] || {
  echo "no latest release for ${UPSTREAM}" >&2
  exit 1
}
version="${tag#v}"
echo "crw — latest ${version}" >&2

base="https://github.com/${UPSTREAM}/releases/download/${tag}"
sums="$(curl -fsSL "${base}/SHA256SUMS")"

ASSET_MAC_ARM="crw-darwin-arm64.tar.gz"
ASSET_MAC_X64="crw-darwin-x64.tar.gz"
ASSET_LNX_ARM="crw-linux-arm64.tar.gz"
ASSET_LNX_X64="crw-linux-x64.tar.gz"

DL="${WORK}/dl"
mkdir -p "$DL"

# Fetch one asset to $DL, check it against upstream's SHA256SUMS, echo the hash.
# Deterministic paths (rather than mktemp) so the bottle step can find the
# linux/x64 tarball without a global set from inside a subshell.
verify_asset() {
  asset="$1"
  want="$(awk -v a="$asset" '$2 == a { print $1 }' <<<"$sums")"
  [ -n "$want" ] || {
    echo "missing ${asset} in SHA256SUMS" >&2
    exit 1
  }
  echo "  fetching ${asset} …" >&2
  curl -fsSL "${base}/${asset}" -o "${DL}/${asset}"
  got="$(sha256of "${DL}/${asset}")"
  [ "$got" = "$want" ] || {
    echo "checksum mismatch for ${asset}: ${got} != ${want}" >&2
    exit 1
  }
  echo "$want"
}

SHA_MAC_ARM="$(verify_asset "$ASSET_MAC_ARM")"
SHA_MAC_X64="$(verify_asset "$ASSET_MAC_X64")"
SHA_LNX_ARM="$(verify_asset "$ASSET_LNX_ARM")"
SHA_LNX_X64="$(verify_asset "$ASSET_LNX_X64")"

# Build the x86_64_linux bottle: a tar.gz of the keg layout Homebrew installs
# (crw/<version>/bin/crw). No compilation — just repackaging.
stage="${WORK}/stage"
keg="${stage}/crw/${version}/bin"
rm -rf "$stage"
mkdir -p "$keg"
tar xzf "${DL}/${ASSET_LNX_X64}" -C "$keg" crw
chmod +x "${keg}/crw"
bottle="${WORK}/crw-${version}.x86_64_linux.bottle.tar.gz"
rm -f "$WORK"/*.bottle.tar.gz
(cd "$stage" && tar czf "$bottle" crw)
rm -rf "$stage" "$DL"
BOTTLE_SHA256="$(sha256of "$bottle")"
echo "  built bottle $(basename "$bottle")" >&2

root_url="https://github.com/${REPO}/releases/download/v${version}"

cat >"$OUT" <<EOF
# Auto-generated by crw-brew from upstream's GitHub releases.
# Do not edit by hand — run \`update.sh\` (CI keeps it current).
class Crw < Formula
  desc "Turn URLs into clean markdown or JSON — scrape, crawl, search, MCP server"
  homepage "https://github.com/${UPSTREAM}"
  version "${version}"
  # Upstream declares the deprecated bare "AGPL-3.0" and ships AGPLv3 with no
  # "or later" clause, which is SPDX "AGPL-3.0-only".
  license "AGPL-3.0-only"

  # Prebuilt x86_64 Linux bottle so \`brew install\` pours it with no C compiler
  # (Homebrew-on-Linux otherwise requires one — a problem on atomic distros).
  # macOS and other arches fall back to the upstream url below; macOS always has
  # clang via the required Command Line Tools, so no bottle is needed.
  bottle do
    root_url "${root_url}"
    sha256 cellar: :any_skip_relocation, x86_64_linux: "${BOTTLE_SHA256}"
  end

  on_macos do
    on_arm do
      url "${base}/${ASSET_MAC_ARM}"
      sha256 "${SHA_MAC_ARM}"
    end
    on_intel do
      url "${base}/${ASSET_MAC_X64}"
      sha256 "${SHA_MAC_X64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/${ASSET_LNX_ARM}"
      sha256 "${SHA_LNX_ARM}"
    end
    on_intel do
      url "${base}/${ASSET_LNX_X64}"
      sha256 "${SHA_LNX_X64}"
    end
  end

  def install
    bin.install "crw"
  end

  def caveats
    <<~EOS
      crw runs fully locally — no account, no API key:

        crw example.com                 # page as markdown on stdout
        crw mcp                         # embedded MCP server for AI agents
        crw doctor                      # check renderer, search, proxy, ports

      When a page returns thin content, crw escalates to its own JS renderer and
      says so on stderr. Sites behind a Cloudflare challenge or DataDome return
      the interstitial rather than the article — clearing those needs a real
      browser session, not a renderer.

      \`crw search\` needs a backend: either a local one or the hosted CRW Cloud
      via \`crw setup\` (paid, with a free credit allowance). Scraping, crawling,
      mapping and the MCP server need none of it.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/crw --version")
  end
end
EOF

echo "wrote $OUT (v$version) + $(basename "$bottle")" >&2
echo "$version"
